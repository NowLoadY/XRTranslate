//! Centralized UI copy and translations.
//!
//! UI code always uses the English source text as a key. Adding a language is
//! a single consolidated table addition rather than separate arrays per language.
use serde::{Deserialize, Serialize};
use std::borrow::Cow;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum UiLanguage {
    #[default]
    English,
    Chinese,
    Japanese,
    Korean,
    Russian,
}

impl UiLanguage {
    pub const ALL: [Self; 5] = [
        Self::English,
        Self::Chinese,
        Self::Japanese,
        Self::Korean,
        Self::Russian,
    ];

    pub const fn display_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Chinese => "中文",
            Self::Japanese => "日本語",
            Self::Korean => "한국어",
            Self::Russian => "Русский",
        }
    }
}

const USAGE_NOTICE_KEYS: [&str; 3] = [
    "Voice cloning is for your own voice only. Do not clone, imitate, or impersonate another person's voice.",
    "Do not use XRTranslate for unlawful purposes. Comply with the laws and regulations applicable in your country or region, and respect privacy, personality rights, and intellectual property rights.",
    "Speech recognition, translation, and synthesized speech may contain errors. Verify important content before use.",
];

/// Looks up a fixed UI string from the consolidated multi-language dictionary.
/// Missing translations intentionally fall back to the English source key.
pub fn tr(language: UiLanguage, english: &'static str) -> &'static str {
    match language {
        UiLanguage::English => english,
        UiLanguage::Chinese => DICTIONARY
            .iter()
            .find_map(|(key, zh, _ja, _ko, _ru)| (*key == english).then_some(*zh))
            .unwrap_or(english),
        UiLanguage::Japanese => DICTIONARY
            .iter()
            .find_map(|(key, _zh, ja, _ko, _ru)| (*key == english).then_some(*ja))
            .unwrap_or(english),
        UiLanguage::Korean => DICTIONARY
            .iter()
            .find_map(|(key, _zh, _ja, ko, _ru)| (*key == english).then_some(*ko))
            .unwrap_or(english),
        UiLanguage::Russian => DICTIONARY
            .iter()
            .find_map(|(key, _zh, _ja, _ko, ru)| (*key == english).then_some(*ru))
            .unwrap_or(english),
    }
}

pub fn usage_notice_items(language: UiLanguage) -> [&'static str; 3] {
    USAGE_NOTICE_KEYS.map(|item| tr(language, item))
}

/// Dynamic counterpart for status text that originates outside the UI layer.
pub fn tr_dynamic<'a>(language: UiLanguage, english: &'a str) -> Cow<'a, str> {
    match language {
        UiLanguage::English => Cow::Borrowed(english),
        UiLanguage::Chinese => {
            if let Some((_, zh, _, _, _)) =
                DICTIONARY.iter().find(|(key, _, _, _, _)| *key == english)
            {
                Cow::Borrowed(zh)
            } else {
                Cow::Borrowed(english)
            }
        }
        UiLanguage::Japanese => {
            if let Some((_, _, ja, _, _)) =
                DICTIONARY.iter().find(|(key, _, _, _, _)| *key == english)
            {
                Cow::Borrowed(ja)
            } else {
                Cow::Borrowed(english)
            }
        }
        UiLanguage::Korean => {
            if let Some((_, _, _, ko, _)) =
                DICTIONARY.iter().find(|(key, _, _, _, _)| *key == english)
            {
                Cow::Borrowed(ko)
            } else {
                Cow::Borrowed(english)
            }
        }
        UiLanguage::Russian => {
            if let Some((_, _, _, _, ru)) =
                DICTIONARY.iter().find(|(key, _, _, _, _)| *key == english)
            {
                Cow::Borrowed(ru)
            } else {
                Cow::Borrowed(english)
            }
        }
    }
}

